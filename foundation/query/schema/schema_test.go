// ExampleOperation_Statements demonstrates compiling every published statement
// with checked errors, without opening a database or executing the DDL.
func ExampleOperation_Statements() {
	op := schema.Create("tags", func(table *schema.Table) {
		table.ID()
		table.String("name", 50).Unique()
	})

	for _, definition := range op.Statements() {
		statement, err := definition.BuildFor(query.Postgres)

		if err != nil {
			fmt.Println(err)

			return
		}

		fmt.Println(statement.SQL())
	}
	// Output:
	// CREATE TABLE "tags" ("id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "name" varchar(50) NOT NULL)
	// CREATE UNIQUE INDEX "tags_name_key" ON "tags" ("name")
}

// requireSQL fails unless op compiles for dialect to exactly wants, one SQL
// text per statement, without arguments.
func requireSQL(t *testing.T, op schema.Operation, dialect query.Dialect, wants ...string) {
	t.Helper()

	if err := op.Err(); err != nil {
		t.Fatalf("%s: Err() = %v", dialect, err)
	}

	statements := op.Statements()

	if len(statements) != len(wants) {
		t.Fatalf("%s: got %d statements, want %d", dialect, len(statements), len(wants))
	}

	for index, want := range wants {
		statement, err := statements[index].BuildFor(dialect)

		if err != nil {
			t.Fatalf("%s statement %d: %v", dialect, index, err)
		}

		if statement.SQL() != want {
			t.Fatalf("%s statement %d:\n got %s\nwant %s", dialect, index, statement.SQL(), want)
		}

		if len(statement.Args()) != 0 {
			t.Fatalf("%s statement %d: unexpected args %v", dialect, index, statement.Args())
		}
	}
}

// requireInvalid fails unless op reports ErrInvalidQuery, but not
// ErrUnsupported, from Err and from every statement.
func requireInvalid(t *testing.T, op schema.Operation) {
	t.Helper()

	err := op.Err()

	if !errors.Is(err, query.ErrInvalidQuery) || errors.Is(err, query.ErrUnsupported) {
		t.Fatalf("Err() = %v, want a plain ErrInvalidQuery", err)
	}

	for _, statement := range op.Statements() {
		if _, buildErr := statement.BuildFor(query.Postgres); !errors.Is(buildErr, query.ErrInvalidQuery) {
			t.Fatalf("BuildFor = %v, want ErrInvalidQuery", buildErr)
		}
	}
}

// requireUnsupported fails unless a statement of op fails for dialect with
// both ErrUnsupported and ErrInvalidQuery while Err() stays nil.
func requireUnsupported(t *testing.T, op schema.Operation, dialect query.Dialect) {
	t.Helper()

	if err := op.Err(); err != nil {
		t.Fatalf("Err() = %v, want nil", err)
	}

	for _, statement := range op.Statements() {
		_, err := statement.BuildFor(dialect)

		if err == nil {
			continue
		}

		if !errors.Is(err, query.ErrUnsupported) || !errors.Is(err, query.ErrInvalidQuery) {
			t.Fatalf("%s: got %v, want ErrUnsupported and ErrInvalidQuery", dialect, err)
		}

		return
	}

	t.Fatalf("%s: every statement compiled, want ErrUnsupported", dialect)
}

// TestCreateUsers verifies the flagship create on every dialect.
func TestCreateUsers(t *testing.T) {
	t.Parallel()

	define := func(table *schema.Table) {
		table.ID()
		table.ForeignID("tenant_id", "tenants").OnDelete(schema.Cascade)
		table.String("email", 255)
		table.Text("bio").Nullable()
		table.Boolean("active").Default(true)
		table.Timestamps()
		table.Unique("tenant_id", "email")
		table.Index("bio")
	}
	op := schema.Create("users", define)

	requireSQL(t, op, query.ANSI,
		`CREATE TABLE "users" ("id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "tenant_id" bigint NOT NULL, `+
			`"email" varchar(255) NOT NULL, "bio" text, "active" boolean NOT NULL DEFAULT TRUE, `+
			`"created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, `+
			`"updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP, `+
			`CONSTRAINT "users_tenant_id_fkey" FOREIGN KEY ("tenant_id") REFERENCES "tenants" ("id") ON DELETE CASCADE)`,
		`CREATE UNIQUE INDEX "users_tenant_id_email_key" ON "users" ("tenant_id", "email")`,
		`CREATE INDEX "users_bio_index" ON "users" ("bio")`)
	requireSQL(t, schema.CreateIfNotExists("users", define), query.Postgres,
		`CREATE TABLE IF NOT EXISTS "users" ("id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "tenant_id" bigint NOT NULL, `+
			`"email" varchar(255) NOT NULL, "bio" text, "active" boolean NOT NULL DEFAULT TRUE, `+
			`"created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, `+
			`"updated_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, `+
			`CONSTRAINT "users_tenant_id_fkey" FOREIGN KEY ("tenant_id") REFERENCES "tenants" ("id") ON DELETE CASCADE)`,
		`CREATE UNIQUE INDEX IF NOT EXISTS "users_tenant_id_email_key" ON "users" ("tenant_id", "email")`,
		`CREATE INDEX IF NOT EXISTS "users_bio_index" ON "users" ("bio")`)
	requireSQL(t, op, query.MySQL,
		"CREATE TABLE `users` (`id` bigint NOT NULL AUTO_INCREMENT PRIMARY KEY, `tenant_id` bigint NOT NULL, "+
			"`email` varchar(255) NOT NULL, `bio` text, `active` boolean NOT NULL DEFAULT 1, "+
			"`created_at` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), "+
			"`updated_at` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), "+
			"CONSTRAINT `users_tenant_id_fkey` FOREIGN KEY (`tenant_id`) REFERENCES `tenants` (`id`) ON DELETE CASCADE)",
		"CREATE UNIQUE INDEX `users_tenant_id_email_key` ON `users` (`tenant_id`, `email`)",
		"CREATE INDEX `users_bio_index` ON `users` (`bio`)")
	requireSQL(t, op, query.SQLite,
		`CREATE TABLE "users" ("id" INTEGER PRIMARY KEY AUTOINCREMENT, "tenant_id" INTEGER NOT NULL, `+
			`"email" TEXT NOT NULL, "bio" TEXT, "active" INTEGER NOT NULL DEFAULT 1, `+
			`"created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, `+
			`"updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, `+
			`CONSTRAINT "users_tenant_id_fkey" FOREIGN KEY ("tenant_id") REFERENCES "tenants" ("id") ON DELETE CASCADE)`,
		`CREATE UNIQUE INDEX "users_tenant_id_email_key" ON "users" ("tenant_id", "email")`,
		`CREATE INDEX "users_bio_index" ON "users" ("bio")`)
}

