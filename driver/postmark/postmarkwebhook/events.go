package postmarkwebhook

import (
	"time"

	"arkoren.dev/core/http/webhook"
)

// Delivered decodes successful delivery notifications without credentials.
// Delivery means acceptance by the receiving mail server, not by a human.
// Example: receiver.Handle(postmarkwebhook.Delivered, acceptDelivery)
var Delivered = webhook.NewEvent("Delivery", decode[Delivery])

// Bounced decodes delivery failures, including the provider's bounce category.
// Not every bounce makes a recipient inactive; inspect Inactive explicitly.
// Example: receiver.Handle(postmarkwebhook.Bounced, acceptBounce)
var Bounced = webhook.NewEvent("Bounce", decode[Bounce])

// SpamComplaint decodes abuse reports using the same fields as Bounce.
// These reports can include sensitive recipient and diagnostic information.
// Example: receiver.Handle(postmarkwebhook.SpamComplaint, acceptComplaint)
var SpamComplaint = webhook.NewEvent("SpamComplaint", decode[Bounce])

// Opened decodes tracking observations, not proof that a human read the email.
// Repeated opens for one message are distinct notifications.
// Example: receiver.Handle(postmarkwebhook.Opened, acceptOpen)
var Opened = webhook.NewEvent("Open", decode[Tracking])

// Clicked decodes link tracking, which can also be generated by automated scanners.
// Repeated clicks for one message are distinct notifications.
// Example: receiver.Handle(postmarkwebhook.Clicked, acceptClick)
var Clicked = webhook.NewEvent("Click", decode[Tracking])

// SubscriptionChanged decodes recipient suppression changes, including removals.
// SuppressSending determines the resulting state, not the event name alone.
// Example: receiver.Handle(postmarkwebhook.SubscriptionChanged, acceptChange)
var SubscriptionChanged = webhook.NewEvent("SubscriptionChange", decode[Subscription])

// Inbound decodes received email on a source created by NewInbound.
// Sender addresses and content are untrusted even after endpoint authentication.
// Example: receiver.Handle(postmarkwebhook.Inbound, acceptEmail)
var Inbound = webhook.NewEvent("Inbound", decode[Email])

// Message contains shared outbound message context. Fields omitted by Postmark
// retain zero values; MessageID is not a unique tracking-event identity.
// Example: _ = postmarkwebhook.Message{MessageID: "message-id"}
type Message struct {
	// MessageID identifies the email, not an individual open or click.
	// Example: _ = notification.MessageID
	MessageID string `json:"MessageID"`
	// MessageStream is the stream configured in Postmark.
	// Example: _ = notification.MessageStream
	MessageStream string `json:"MessageStream"`
	// Recipient is the destination address for delivery and tracking events.
	// Example: _ = notification.Recipient
	Recipient string `json:"Recipient"`
	// Tag is the application's optional message label.
	// Example: _ = notification.Tag
	Tag string `json:"Tag"`
	// Metadata carries application-supplied string attributes.
	// Example: _ = notification.Metadata["order"]
	Metadata map[string]string `json:"Metadata"`
	// ServerID identifies the server when supplied by the event type.
	// Example: _ = notification.ServerID
	ServerID int64 `json:"ServerID"`
}

// Delivery reports mail-server acceptance with its timestamp and SMTP response.
// It does not promise inbox placement or reading.
// Example: _ = postmarkwebhook.Delivery{}.DeliveredAt
type Delivery struct {
	// Message supplies shared message context.
	// Example: _ = notification.MessageID
	Message
	// DeliveredAt is the provider's acceptance time, decoded from ISO 8601.
	// Example: _ = notification.DeliveredAt.UTC()
	DeliveredAt time.Time `json:"DeliveredAt"`
	// Details contains the remote mail server's response and may be sensitive.
	// Example: _ = notification.Details
	Details string `json:"Details"`
}

// Bounce describes a bounce or spam complaint. Extra provider fields are ignored;
// use Envelope with a custom event if full raw diagnostics are required.
// Example: _ = postmarkwebhook.Bounce{Inactive: true}
type Bounce struct {
	// Message supplies shared context; Email is the affected address here.
	// Example: _ = notification.MessageID
	Message
	// ID is the provider's numeric bounce or complaint identifier.
	// Example: _ = notification.ID
	ID int64 `json:"ID"`
	// Type is the provider category, such as HardBounce or SpamComplaint.
	// Example: _ = notification.Type
	Type string `json:"Type"`
	// Email is the affected recipient address.
	// Example: _ = notification.Email
	Email string `json:"Email"`
	// Description is the provider's explanation, not a client-safe error.
	// Example: _ = notification.Description
	Description string `json:"Description"`
	// BouncedAt is the provider's event time for bounces and complaints.
	// Example: _ = notification.BouncedAt.UTC()
	BouncedAt time.Time `json:"BouncedAt"`
	// Inactive reports whether Postmark deactivated the address.
	// Example: _ = notification.Inactive
	Inactive bool `json:"Inactive"`
}

// Tracking contains useful open and click fields. Click-only fields remain empty
// for opens; FirstOpen is only meaningful for open events.
// Example: _ = postmarkwebhook.Tracking{OriginalLink: "https://example.com"}
type Tracking struct {
	// Message supplies shared message context.
	// Example: _ = notification.MessageID
	Message
	// ReceivedAt is the provider's observation time, not local receipt time.
	// Example: _ = notification.ReceivedAt.UTC()
	ReceivedAt time.Time `json:"ReceivedAt"`
	// FirstOpen distinguishes the first recorded open for the message.
	// Example: _ = notification.FirstOpen
	FirstOpen bool `json:"FirstOpen"`
	// OriginalLink is the original clicked URL and may contain private tokens.
	// Example: _ = notification.OriginalLink
	OriginalLink string `json:"OriginalLink"`
	// ClickLocation is the provider's body location, such as HTML.
	// Example: _ = notification.ClickLocation
	ClickLocation string `json:"ClickLocation"`
	// UserAgent describes the opener or clicker and is untrusted input.
	// Example: _ = notification.UserAgent
	UserAgent string `json:"UserAgent"`
}

// Subscription reports a suppression-state change. MessageID can be absent for
// changes not associated with a message; do not require it for routing.
// Example: _ = postmarkwebhook.Subscription{SuppressSending: true}
type Subscription struct {
	// Message supplies stream and recipient context.
	// Example: _ = notification.Recipient
	Message
	// ChangedAt is when the suppression changed at Postmark.
	// Example: _ = notification.ChangedAt.UTC()
	ChangedAt time.Time `json:"ChangedAt"`
	// SuppressSending is the resulting suppression state.
	// Example: _ = notification.SuppressSending
	SuppressSending bool `json:"SuppressSending"`
	// Origin identifies what initiated the change, such as Recipient.
	// Example: _ = notification.Origin
	Origin string `json:"Origin"`
	// SuppressionReason contains the provider reason, when supplied.
	// Example: _ = notification.SuppressionReason
	SuppressionReason string `json:"SuppressionReason"`
}

// Email contains parsed inbound email. Date remains a string because the sending
// mail server chooses its format. HTML, sender claims and attachments are untrusted.
// Attachments and full address structures remain accessible through Envelope.
// Example: _ = postmarkwebhook.Email{Subject: "Support request"}
type Email struct {
	// MessageID identifies the received email across processing retries.
	// Example: _ = notification.MessageID
	MessageID string `json:"MessageID"`
	// From is the sender's address claim, not an authenticated application user.
	// Example: _ = notification.From
	From string `json:"From"`
	// To contains the formatted recipient list.
	// Example: _ = notification.To
	To string `json:"To"`
	// Subject is untrusted message subject text.
	// Example: _ = notification.Subject
	Subject string `json:"Subject"`
	// Date retains the sender-selected timestamp format unchanged.
	// Example: _ = notification.Date
	Date string `json:"Date"`
	// TextBody is the plain text content, possibly empty.
	// Example: _ = notification.TextBody
	TextBody string `json:"TextBody"`
	// HTMLBody is unsanitized HTML; never render it without sanitization.
	// Example: _ = notification.HTMLBody
	HTMLBody string `json:"HtmlBody"`
	// StrippedTextReply is Postmark's extracted reply text when available.
	// Example: _ = notification.StrippedTextReply
	StrippedTextReply string `json:"StrippedTextReply"`
}
