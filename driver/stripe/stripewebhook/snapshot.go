package stripewebhook

import (
	"encoding/json/jsontext"
	"encoding/json/v2"
	"errors"
	"strings"
	"time"

	"github.com/stripe/stripe-go/v87"

	"arkoren.dev/core/service/payment"
)

// resource contains the required identity and discriminator shared by snapshots.
// Status is optional at this layer because native event schemas differ.
type resource struct {
	// ID is the native resource identity, not the event delivery identity.
	ID string `json:"id"`
	// Object discriminates the native Stripe resource schema.
	Object string `json:"object"`
	// Status preserves the native resource's state without event-type inference.
	Status string `json:"status"`
}

// checkoutSnapshot contains only facts needed for a completed-flow observation.
type checkoutSnapshot struct {
	// resource supplies checkout identity, object discriminator, and native state.
	resource
	// AmountTotal is optional so an absent amount is not invented as zero.
	AmountTotal *int64 `json:"amount_total"`
	// Currency is the amount's lowercase Stripe currency code.
	Currency string `json:"currency"`
	// PaymentIntent may be an expanded object, a native ID, or null.
	PaymentIntent jsontext.Value `json:"payment_intent"`
	// Subscription may be an expanded object, a native ID, or null.
	Subscription jsontext.Value `json:"subscription"`
}

// moneySnapshot serves PaymentIntent and refund snapshots, whose money fields
// have identical native names and must remain interpreted in the same units.
type moneySnapshot struct {
	// resource supplies native identity, discriminator, and status.
	resource
	// Amount retains absent versus observed-zero amounts.
	Amount *int64 `json:"amount"`
	// Currency identifies minor units; no amount conversion or rounding occurs.
	Currency string `json:"currency"`
	// PaymentIntent identifies a refund's original payment, if present.
	PaymentIntent jsontext.Value `json:"payment_intent"`
}

// invoiceSnapshot preserves aggregate settlement and the modern parent relation.
// It deliberately has no invented PaymentIntent or subscription top-level field.
type invoiceSnapshot struct {
	// resource supplies invoice identity, discriminator, and status.
	resource
	// AmountPaid is the aggregate paid amount, not proof of a fresh charge.
	AmountPaid *int64 `json:"amount_paid"`
	// AmountDue is the invoice amount requested, used for failed-attempt events.
	AmountDue *int64 `json:"amount_due"`
	// Currency identifies the observed invoice amount's minor units.
	Currency string `json:"currency"`
	// Parent carries the subscription-details relation used by this API version.
	Parent *struct {
		// SubscriptionDetails is absent on invoices not generated by a subscription.
		SubscriptionDetails *struct {
			// Subscription is a native ID, expanded snapshot, or null.
			Subscription jsontext.Value `json:"subscription"`
		} `json:"subscription_details"`
	} `json:"parent"`
}

// invoicePaymentSnapshot represents settlement of one invoice-payment resource.
// It is deliberately distinct from aggregate invoice settlement.
type invoicePaymentSnapshot struct {
	// resource supplies invoice-payment identity, discriminator, and status.
	resource
	// AmountPaid is the individual invoice-payment settlement amount.
	AmountPaid *int64 `json:"amount_paid"`
	// Currency identifies the amount's Stripe minor units.
	Currency string `json:"currency"`
	// Invoice is present only when Stripe supplies the linked invoice.
	Invoice jsontext.Value `json:"invoice"`
	// Payment carries the settlement's native resource family and relation.
	Payment *struct {
		// Type selects payment_intent, charge, or payment_record settlement.
		Type string `json:"type"`
		// PaymentIntent is used only for payment_intent settlements.
		PaymentIntent jsontext.Value `json:"payment_intent"`
	} `json:"payment"`
}

// errSnapshot is safe to report without leaking authenticated provider JSON.
// It does not wrap webhook.ErrRejected: schema failures require a 503 response.
var errSnapshot = errors.New("stripe webhook: unsupported snapshot schema or api version")

// decodeSnapshot gates typed resource decoding on an exact SDK API version.
// Using json/v2 and our small DTOs avoids SDK v1 custom-unmarshal dependencies.
func decodeSnapshot[T any](envelope Envelope) (T, error) {
	var result T

	if envelope.APIVersion != stripe.APIVersion {
		return result, errSnapshot
	}

	if err := json.Unmarshal(envelope.Data.Object, &result); err != nil {
		return result, errSnapshot
	}

	return result, nil
}

// observation starts the shared event facts and verifies the resource schema.
// Delivery ID and event type belong exclusively to core's Delivery envelope.
func observation(envelope Envelope, snapshot resource, object string) (payment.Observation, error) {
	if snapshot.ID == "" || snapshot.Object != object || snapshot.Status == "" {
		return payment.Observation{}, errSnapshot
	}

	result := payment.Observation{NativeStatus: snapshot.Status}

	if envelope.CreatedAt > 0 {
		result.OccurredAt = time.Unix(envelope.CreatedAt, 0).UTC()
	}

	return result, nil
}

// relatedID handles the native expandable relation without guessing absent IDs.
// Expanded objects must contain a nonempty string ID; malformed relations fail.
func relatedID(value jsontext.Value) (string, error) {
	if len(value) == 0 || string(value) == "null" {
		return "", nil
	}

	var id string

	if value.Kind() == '"' {
		if err := json.Unmarshal(value, &id); err != nil {
			return "", errSnapshot
		}

		return id, nil
	}

	var snapshot struct {
		// ID is the identity from an expanded relation; no other field is decoded.
		ID string `json:"id"`
	}

	if err := json.Unmarshal(value, &snapshot); err != nil {
		return "", errSnapshot
	}

	if snapshot.ID == "" {
		return "", errSnapshot
	}

	return snapshot.ID, nil
}

// observedMoney detaches a known amount and enforces the core's audited currency
// set. Both fields absent means unknown; partially present money is invalid.
func observedMoney(amount *int64, currency string) (*payment.Money, error) {
	if amount == nil && currency == "" {
		return nil, nil
	}

	if amount == nil {
		return nil, errSnapshot
	}

	result := &payment.Money{Amount: *amount, Currency: strings.ToUpper(currency)}

	if err := result.Validate(); err != nil {
		return nil, errSnapshot
	}

	return result, nil
}
